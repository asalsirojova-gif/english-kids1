const $ = (id) => document.getElementById(id);
const startScreen = $("startScreen"), quizScreen = $("quizScreen"), resultScreen = $("resultScreen");
const optionsEl = $("options"), feedbackEl = $("feedback"), qualityText = $("qualityText"), qualityEnglish = $("qualityEnglish");
let current = 0, correct = 0, wrong = 0, locked = false;

const cheer = ["Amazing! 🌟", "Great job! 🎉", "Excellent! 🌈", "MashaAllah! ✨"];
const tryAgain = ["Try one more time! 🌸", "Almost! Have another look! 🌼", "Keep going! 💪🌈"];

function shuffle(arr){
  const a = [...arr];
  for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]]}
  return a;
}
function show(screen){
  [startScreen,quizScreen,resultScreen].forEach(s=>s.classList.remove("active"));
  screen.classList.add("active");
  window.scrollTo({top:0,behavior:"smooth"});
}
function renderQuestion(){
  locked=false; feedbackEl.className="feedback"; feedbackEl.textContent="";
  const q=DATA.questions[current], target=DATA.letters[q.target];
  $("questionCounter").textContent=`Question ${current+1} of ${DATA.questions.length}`;
  $("scoreBadge").textContent=`⭐ ${correct}`;
  $("progressBar").style.width=`${((current+1)/DATA.questions.length)*100}%`;
  $("questionText").innerHTML=`Which one is <span>${target.char}</span>?`;
  qualityText.textContent=target.sifat.split(";")[0];
  qualityEnglish.textContent="Tajweed quality for this letter.";
  optionsEl.innerHTML="";
  shuffle(q.options).forEach(idx=>{
    const btn=document.createElement("button");
    btn.className="option"; btn.type="button"; btn.textContent=DATA.letters[idx].char;
    btn.setAttribute("aria-label",`Arabic letter ${DATA.letters[idx].name}`);
    btn.addEventListener("click",()=>answer(idx,btn,target));
    optionsEl.appendChild(btn);
  });
}
function answer(idx,btn,target){
  if(locked)return;
  const isCorrect=idx===targetIndex();
  if(isCorrect){
    locked=true; correct++; btn.classList.add("correct");
    [...optionsEl.children].forEach(b=>b.classList.add("disabled"));
    feedbackEl.className="feedback good";
    feedbackEl.textContent=cheer[current%cheer.length];
    qualityText.textContent=target.sifat;
    qualityEnglish.textContent="Nice! Remember: a Sifah describes a characteristic of the letter's sound.";
    setTimeout(next,850);
  }else{
    wrong++; btn.classList.add("wrong"); btn.classList.add("disabled");
    feedbackEl.className="feedback try"; feedbackEl.textContent=tryAgain[current%tryAgain.length];
    qualityText.textContent=target.sifat;
    qualityEnglish.textContent="Look carefully and try again.";
    $("scoreBadge").textContent=`⭐ ${correct}`;
  }
}
function targetIndex(){ return DATA.questions[current].target; }
function next(){
  if(current<DATA.questions.length-1){current++;renderQuestion()}
  else showResult();
}
function showResult(){
  show(resultScreen);
  $("correctResult").textContent=correct;
  $("wrongResult").textContent=wrong;
  $("percentResult").textContent=Math.round(correct/DATA.questions.length*100)+"%";
  const pct=correct/DATA.questions.length;
  $("resultMessage").textContent =
    pct>=.9 ? "🌸 MashaAllah! Excellent work! May your knowledge grow! 🌸" :
    pct>=.7 ? "🌟 Well done! Keep practicing and you will shine! 🌟" :
    "🌈 Good effort! Practice makes you stronger! Keep going! 🌈";
}
function start(){
  current=0;correct=0;wrong=0;show(quizScreen);renderQuestion();
}
$("startBtn").addEventListener("click",start);
$("restartBtn").addEventListener("click",start);
